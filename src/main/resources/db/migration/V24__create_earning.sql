CREATE TABLE earning (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT         NOT NULL REFERENCES signature (id),
    value_plataform NUMERIC(19, 2) NOT NULL,
    value_producer  NUMERIC(19, 2) NOT NULL,
    created_at      TIMESTAMP      DEFAULT now(),
    updated_at      TIMESTAMP      DEFAULT now()
);
CREATE INDEX idx_earning_subscription_id ON earning (subscription_id);
